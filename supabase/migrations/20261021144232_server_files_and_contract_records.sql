-- Private, per-user file storage and server-side contract persistence.

INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'growmoney-files',
  'growmoney-files',
  false,
  10485760,
  ARRAY[
    'image/jpeg', 'image/png', 'image/webp', 'image/gif', 'image/svg+xml',
    'application/pdf', 'application/msword',
    'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    'application/vnd.ms-excel',
    'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
  ]
)
ON CONFLICT (id) DO UPDATE SET
  public = EXCLUDED.public,
  file_size_limit = EXCLUDED.file_size_limit,
  allowed_mime_types = EXCLUDED.allowed_mime_types;

CREATE TABLE IF NOT EXISTS public.gm_files (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  categoria text NOT NULL CHECK (categoria IN ('fotos', 'arquivos', 'contratos')),
  bucket_id text NOT NULL DEFAULT 'growmoney-files' CHECK (bucket_id = 'growmoney-files'),
  object_path text NOT NULL UNIQUE,
  original_name text NOT NULL,
  content_type text NOT NULL,
  size_bytes bigint NOT NULL CHECK (size_bytes >= 0 AND size_bytes <= 10485760),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (split_part(object_path, '/', 1) = user_id::text),
  CHECK (split_part(object_path, '/', 2) = categoria)
);

ALTER TABLE public.gm_files ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.gm_files FROM anon, authenticated;
GRANT SELECT, INSERT, DELETE ON public.gm_files TO authenticated;

DROP POLICY IF EXISTS gm_files_select_own ON public.gm_files;
CREATE POLICY gm_files_select_own ON public.gm_files
  FOR SELECT TO authenticated USING (user_id = (SELECT auth.uid()));
DROP POLICY IF EXISTS gm_files_insert_own ON public.gm_files;
CREATE POLICY gm_files_insert_own ON public.gm_files
  FOR INSERT TO authenticated WITH CHECK (
    user_id = (SELECT auth.uid())
    AND split_part(object_path, '/', 1) = (SELECT auth.uid())::text
    AND split_part(object_path, '/', 2) = categoria
  );
DROP POLICY IF EXISTS gm_files_delete_own ON public.gm_files;
CREATE POLICY gm_files_delete_own ON public.gm_files
  FOR DELETE TO authenticated USING (user_id = (SELECT auth.uid()));

DROP POLICY IF EXISTS gm_files_storage_select_own ON storage.objects;
CREATE POLICY gm_files_storage_select_own ON storage.objects
  FOR SELECT TO authenticated USING (
    bucket_id = 'growmoney-files'
    AND (storage.foldername(name))[1] = (SELECT auth.uid())::text
  );
DROP POLICY IF EXISTS gm_files_storage_insert_own ON storage.objects;
CREATE POLICY gm_files_storage_insert_own ON storage.objects
  FOR INSERT TO authenticated WITH CHECK (
    bucket_id = 'growmoney-files'
    AND (storage.foldername(name))[1] = (SELECT auth.uid())::text
    AND (storage.foldername(name))[2] IN ('fotos', 'arquivos', 'contratos')
  );
DROP POLICY IF EXISTS gm_files_storage_update_own ON storage.objects;
CREATE POLICY gm_files_storage_update_own ON storage.objects
  FOR UPDATE TO authenticated USING (
    bucket_id = 'growmoney-files'
    AND (storage.foldername(name))[1] = (SELECT auth.uid())::text
  ) WITH CHECK (
    bucket_id = 'growmoney-files'
    AND (storage.foldername(name))[1] = (SELECT auth.uid())::text
  );
DROP POLICY IF EXISTS gm_files_storage_delete_own ON storage.objects;
CREATE POLICY gm_files_storage_delete_own ON storage.objects
  FOR DELETE TO authenticated USING (
    bucket_id = 'growmoney-files'
    AND (storage.foldername(name))[1] = (SELECT auth.uid())::text
  );

CREATE TABLE IF NOT EXISTS public.gm_contracts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  numero bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  status text NOT NULL CHECK (status IN ('rascunho', 'enviado', 'assinado', 'cancelado')),
  payload jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS gm_contracts_user_numero_idx
  ON public.gm_contracts (user_id, numero DESC);

ALTER TABLE public.gm_contracts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.gm_contracts FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.gm_contracts TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.gm_contracts_numero_seq TO authenticated;

DROP POLICY IF EXISTS gm_contracts_select_own ON public.gm_contracts;
CREATE POLICY gm_contracts_select_own ON public.gm_contracts
  FOR SELECT TO authenticated USING (user_id = (SELECT auth.uid()));
DROP POLICY IF EXISTS gm_contracts_insert_own ON public.gm_contracts;
CREATE POLICY gm_contracts_insert_own ON public.gm_contracts
  FOR INSERT TO authenticated WITH CHECK (user_id = (SELECT auth.uid()));
DROP POLICY IF EXISTS gm_contracts_update_own ON public.gm_contracts;
CREATE POLICY gm_contracts_update_own ON public.gm_contracts
  FOR UPDATE TO authenticated USING (user_id = (SELECT auth.uid()))
  WITH CHECK (user_id = (SELECT auth.uid()));
DROP POLICY IF EXISTS gm_contracts_delete_own ON public.gm_contracts;
CREATE POLICY gm_contracts_delete_own ON public.gm_contracts
  FOR DELETE TO authenticated USING (user_id = (SELECT auth.uid()));
